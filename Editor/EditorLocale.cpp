const char* EditorText(EditorLanguage language, const char* english)
{
    if (language == EditorLanguage::Chinese)
        for (const auto& [key, translation] : Catalog)
            if (key == english)
                return translation;
    return english;
}

std::string EditorLabel(EditorLanguage language, const char* english)
{
    return std::string(EditorText(language, english)) + "###" + english;
}

std::string_view EditorLanguageCode(EditorLanguage language) noexcept
{
    return language == EditorLanguage::Chinese ? "zh-CN" : "en-US";
}

std::optional<EditorLanguage> ParseEditorLanguage(std::string_view code) noexcept
{
    if (code == "en-US")
        return EditorLanguage::English;
    if (code == "zh-CN")
        return EditorLanguage::Chinese;
    return std::nullopt;
}
